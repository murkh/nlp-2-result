class TokenUsage(BaseModel):
    """Token counts and estimated monetary cost for LLM generation."""

    prompt_tokens: int = Field(default=0, description="Tokens consumed by prompt context")
    completion_tokens: int = Field(default=0, description="Tokens generated by LLM")
    total_tokens: int = Field(default=0, description="Total tokens for request")
    estimated_cost_usd: float = Field(
        default=0.0, description="Estimated USD cost based on model token rates"
    )

    def __init__(
        self,
        prompt_tokens: int = 0,
        completion_tokens: int = 0,
        total_tokens: int = 0,
        estimated_cost_usd: float = 0.0,
        **kwargs,
    ):
        calc_total = total_tokens or (prompt_tokens + completion_tokens)
        calc_cost = estimated_cost_usd or (
            prompt_tokens * 0.00000015 + completion_tokens * 0.0000006
        )
        super().__init__(
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=calc_total,
            estimated_cost_usd=round(calc_cost, 6),
            **kwargs,
        )


class ExecutionMetrics(BaseModel):
    """Execution and synthesis latency breakdown in milliseconds."""

    query_generation_ms: float = Field(
        default=0.0, description="LLM query/code generation latency in ms"
    )
    engine_execution_ms: float = Field(
        default=0.0, description="Database or sandbox execution latency in ms"
    )
    synthesis_ms: float = Field(
        default=0.0, description="Natural language answer synthesis latency in ms"
    )
    total_latency_ms: float = Field(
        default=0.0, description="Total end-to-end request latency in ms"
    )

    def __init__(
        self,
        query_generation_ms: float = 0.0,
        engine_execution_ms: float = 0.0,
        synthesis_ms: float = 0.0,
        total_latency_ms: float = 0.0,
        **kwargs,
    ):
        calc_total = total_latency_ms or (query_generation_ms + engine_execution_ms + synthesis_ms)
        super().__init__(
            query_generation_ms=round(query_generation_ms, 2),
            engine_execution_ms=round(engine_execution_ms, 2),
            synthesis_ms=round(synthesis_ms, 2),
            total_latency_ms=round(calc_total, 2),
            **kwargs,
        )


class TabularResult(BaseModel):
    """Standardized representation of structured query results."""

    columns: List[str] = Field(default_factory=list, description="Column names of result table")
    rows: List[Dict[str, Any]] = Field(
        default_factory=list, description="Row records (key-value pairs)"
    )
    row_count: int = Field(default=0, description="Total rows returned (max 20)")
    truncated: bool = Field(default=False, description="Whether result was capped by LIMIT 20")

    def __init__(
        self,
        columns: Optional[List[str]] = None,
        rows: Optional[List[Dict[str, Any]]] = None,
        row_count: Optional[int] = None,
        truncated: bool = False,
        **kwargs,
    ):
        cols = columns or []
        r_list = rows or []
        r_count = row_count if row_count is not None else len(r_list)
        super().__init__(
            columns=cols, rows=r_list, row_count=r_count, truncated=truncated, **kwargs
        )


